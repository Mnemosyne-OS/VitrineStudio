/**
 * Words in Markdown, read as themselves: a `*` or a `[` never becomes markup, nor a
 * `#`, `-` or `1.` that opens a line. Only those: the editor shows the rest as typed.
 */
const md = (s: string) => s.trim().replace(/([\\*_`~[\]])/g, '\\$1').replace(/^([#>+-]|\d+[.)])/, '\\$1');
const section = (title: string, ...lines: string[]) => { const l = lines.filter(Boolean); return l.length ? `### ${title}\n${l.join('\n')}\n\n` : ''; };

/** `measured`: the page loads Vercel's visit counter (site/buildSite.ts `analytics`). */
export interface LegalSite { name: string; email: string; formspree: boolean; form: boolean; socials: boolean; lang: Lang; staged?: boolean; measured?: boolean }

/** The two pages as the site would write them from her fields, in Markdown. */
export function legalMarkdown(l: Legal, site: LegalSite): { notice: string; privacy: string } {
  const w = W[site.lang];
  const owner = l.owner.trim() || site.name;
  const fill = (s: string, v: Record<string, string>) => s.replace(/\{(\w+)\}/g, (_, k: string) => v[k] ?? '');
  const email = site.email.trim();
  const mail = email ? `[${md(email)}](mailto:${email.replace(/[()\s]/g, '')})` : '';
  const multi = (s: string) => s.trim().split('\n').map(md).filter(Boolean);

  const notice = section(w.publisher!, md(owner), md(l.status), l.siret.trim() ? `${w.siret} : ${md(l.siret)}` : '', ...multi(l.address), mail, l.phone.trim() ? `${w.phone} : ${md(l.phone)}` : '')
    + section(w.director!, md(l.director.trim() || owner))
    + section(w.host!, md(l.hostName), ...multi(l.hostAddress))
    + section(w.ip!, md(fill(w.ipText!, { owner: owner.replace(/\.+$/, '') })))
    // Only a site with staged scenes speaks of generated settings.
    + (site.staged ? section(w.images!, md(w.imagesText!)) : '');

  const host = l.hostName.trim();
  const [before, after] = w.rightsText!.split('{email}');
  const privacy = section(w.controller!, md(owner), mail)
    + section(w.data!, md(site.form ? (site.formspree ? w.formSpree! : w.formMail!) : w.noForm!), site.form && site.formspree ? md(w.keep!) : '', host ? md(fill(w.logs!, { host })) : '', site.socials ? md(w.socials!) : '')
    + section(w.cookies!, md(site.measured ? w.cookiesMeasured! : w.cookiesText!), l.notice ? md(w.noticeKept!) : '')
    + (site.measured ? measureSection(site.lang) : '')
    + section(w.rights!, email ? `${md(before!)} ${mail}${md(after ?? '')}` : md(w.rightsNoMail!));
  return { notice: notice.trim(), privacy: privacy.trim() };
}

/** The privacy page's paragraph on the visit counter, in Markdown. */
export const measureSection = (lang: Lang) => section(W[lang].measure!, md(W[lang].measureText!));

/**
 * Her own privacy text, with the paragraph on the visit counter added when
 * the site counts visits and her text does not name it: what the page says
 * must stay true of what the site does, even after she rewrote it.
 */
export function privacyWithMeasure(own: string, site: LegalSite): string {
  if (!site.measured || !own.trim() || /vercel web analytics/i.test(own)) return own;
  return `${own.trim()}\n\n${measureSection(site.lang).trim()}`;
}

export function legalPages(l: Legal, site: LegalSite): SiteLegal {
  const w = W[site.lang];
  const made = legalMarkdown(l, site);
  // Her own text once she has written it; the text from her fields until then.
  const html = (own: string, auto: string) => markdownToHtml(own.trim() || auto, { keepTitle: true });
  const links = `<a href="#${LEGAL_PAGE_ID}">${esc(w.legal!)}</a><a href="#${PRIVACY_PAGE_ID}">${esc(w.privacy!)}</a>`;
  const credit = l.credit ? `<a href="${MNEMOSYNE_URL}" target="_blank" rel="noopener">${esc(w.credit!)}</a>` : '';
  return {
    pages: [{ id: LEGAL_PAGE_ID, title: w.legal!, html: html(l.noticeText, made.notice) }, { id: PRIVACY_PAGE_ID, title: w.privacy!, html: html(privacyWithMeasure(l.privacyText, site), made.privacy) }],
    footer: links + credit,
    ...(l.notice ? { notice: `<span>${esc(w.notice!)}</span><a href="#${PRIVACY_PAGE_ID}">${esc(w.privacy!)}</a>` } : {}),
    close: w.close!,
  };
}

/**
 * Her text says the same as the fields' text: the editor writes Markdown its own
 * way (a heading level, an escape, a blank line), so the two are compared as the
 * page would draw them. An untouched page then keeps following the fields.
 */
export function sameAsFields(text: string, made: string): boolean {
  return markdownToHtml(text.trim(), { keepTitle: true }) === markdownToHtml(made.trim(), { keepTitle: true });
}
